export function getTriadCorrections(
  entity: SelectedEntity,
  context: {
    muscles: Muscle[];
    organs: Organ[];
    meridians: Meridian[];
  }
): TriadCorrectionBundle {
  const primaryMeridian = context.meridians[0];
  const element = primaryMeridian?.element ?? 'Вода';
  const profile = ELEMENT_PROFILES[element] ?? ELEMENT_PROFILES['Вода'];

  const activeMuscle =
    entity.type === 'muscle' ? context.muscles[0] : undefined;
  const activeNutrients =
    activeMuscle?.nutrients.length
      ? activeMuscle.nutrients.join(', ')
      : context.muscles
          .flatMap((m) => m.nutrients)
          .slice(0, 4)
          .join(', ');

  return {
    emotional: {
      domain: 'Эмоциональная коррекция',
      triggerTheme: profile.emotion,
      diagnosticProvocation:
        'Попросите пациента подумать о стрессовом триггере / произнести ключевую фразу при ТЛ лобных бугров — падение тонуса индикатора подтверждает эмоциональную доминанту.',
      correctionMethod: profile.emotionCorrection,
      keyPointsOrNutrients:
        'Лобные бугры (ЭСР) · Височное простукивание · Синхронизация дыхания',
    },
    energetic: {
      domain: 'Энергетическое воздействие',
      triggerTheme: profile.energeticTheme,
      diagnosticProvocation:
        'Проверьте «переключение» (ТЛ К-27 + пупок), полярность (приближение северного/южного полюса магнита или телефона к зоне) и ТЛ сигнальной точки меридиана.',
      correctionMethod:
        'Сначала устраните переключение (массаж К-27 одной рукой + пупок другой, перекрёстный шаг 20 сек), затем сбалансируйте меридиан по правилу Мать–Сын или через Ло-пункт и снимите ЭМИ-провокацию.',
      keyPointsOrNutrients: profile.energeticPoints,
    },
    chemical: {
      domain: 'Химическое воздействие',
      triggerTheme: profile.chemicalTheme,
      diagnosticProvocation:
        'Проведите ольфакторную или сублингвальную провокацию предполагаемым токсином / пищевым аллергеном / реагентом + проверьте НЛ-точки Чапмена на болезненность.',
      correctionMethod:
        'При подтверждении химической реакции отработайте нейролимфатические зоны Чапмена для активации дренажа, поддержите висцеральное скольжение органа и подберите точную нутритивную компенсацию через ретест ММТ.',
      keyPointsOrNutrients: activeNutrients
        ? `${activeNutrients} · ${profile.chemicalDetox}`
        : profile.chemicalDetox,
    },
  };
}

